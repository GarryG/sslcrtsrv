# HTTP paths used to serve the configured client install packages (see
# server_config.json's client_packages - a name -> {path, version,
# description} map, since different client OSes/architectures need
# different install packages: a .deb, an .rpm, a plain tarball, ...).
# Piggybacked on the same port as the main client/server protocol rather
# than a separate port/process; see common/server_utils.py's
# Server.handle_client()/handle_http_download() for the protocol-sniffing
# that makes both work on one port.
#
#   curl -f http://<server-host>:<port>/client-package/<name> -O   (download)
#   curl http://<server-host>:<port>/client-package/                (human overview,
#                                                                     also shown for
#                                                                     any unknown name)
#   curl http://<server-host>:<port>/client-packages                (JSON catalog,
#                                                                     for a client to
#                                                                     check its own
#                                                                     version against)
#
# Always use curl's -f/--fail for the download - without it, curl writes
# whatever comes back (including this endpoint's own 404 overview page, on a
# typo'd/unknown name) straight to the output file with no error, which
# looks exactly like a real, if oddly-small/text-garbled, downloaded package.
CLIENT_PACKAGE_DOWNLOAD_PATH_PREFIX = "/client-package/"
CLIENT_PACKAGES_CATALOG_PATH = "/client-packages"

# Human-readable help/overview page - the *only* thing an unauthenticated
