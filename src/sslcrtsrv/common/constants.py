# web_admin's PHP process runs as a different OS user than server.py (e.g.
# www-data vs. a dedicated sslcrtsrv service account), but needs read/write
# access to keysrv.db and server_config.json, and read access to
# BASE_CONFIG_DIR/DATA_DIR themselves (0700 blocks traversal outright,
# regardless of the individual file's own mode). These are applied only to
# those specific directories/files (see ensure_secure_dir()/write_secure_json()
# in system_utils.py) - everywhere else, e.g. client.py's own config, keeps
# the strict owner-only default.
#
# This intentionally does NOT cover DB_ENCRYPTION_PRIVATE_KEY_FILE (web_admin
# never decrypts, only encrypts using the public half - see db_crypto.py) or
# the private half of the keypair server_config.json's own private_key field
# holds - both must stay owner-only. Deploying this requires a shared unix
# group containing both the server.py service account and the web server's
# user, with BASE_CONFIG_DIR/DATA_DIR and the files below chgrp'd to it; a
# symlink from the web root to these paths does NOT bypass this - Unix
# permission checks apply to the real target path regardless of how it was
# reached, symlink or not.
SHARED_DIR_MODE = 0o750
SHARED_FILE_MODE = 0o660

