# Upper bounds enforced by network_utils.receive_secure_message() on an
# incoming message, before any of it is trusted: real messages here are
# small JSON control/status payloads (the largest legitimate case is a
# `retrieve` response carrying a private key, certificate and intermediate
# chain as PEM text, typically well under 100 KB even for large chains), so
# these are deliberately generous rather than tight. Their purpose is to cap
# the worst case, not to police normal traffic:
#   - MAX_MESSAGE_SIZE / MAX_SIGNATURE_SIZE bound how much the 4-byte
#     length-prefix fields are allowed to claim, so a peer can't make the
#     server buffer gigabytes just by lying about the length.
#   - MAX_DECOMPRESSED_MESSAGE_SIZE bounds the *output* of decompressing
#     that data - zlib's compression ratio can exceed 1000:1, so capping
#     only the wire size does not by itself prevent a small, highly
#     compressible payload from decompressing into a much larger allocation
#     (a "decompression bomb").
MAX_MESSAGE_SIZE = 2 * 1024 * 1024  # 2 MiB
MAX_SIGNATURE_SIZE = 4096  # RSA-PSS signatures are exactly key_size/8 bytes (256 for RSA-2048)
MAX_DECOMPRESSED_MESSAGE_SIZE = 2 * 1024 * 1024  # 2 MiB

# Registration anti-replay settings: bounds how old/skewed a registration
# attempt's timestamp may be, and how long its nonce is remembered server-side
REGISTRATION_NONCE_BYTES = 16
REGISTRATION_TIMESTAMP_WINDOW_SECONDS = 300

# Same idea, for every post-registration `request` message (see
# common/message_utils.py's create_request_message(), common/server_utils.py's
# handle_request()) - kept as separate constants from the registration ones
# above even though they currently share the same values, since registration's
# nonce/timestamp also feed its own HMAC proof and are generated by a
# different code path (common/client_utils.py's register_with_server()).
REQUEST_NONCE_BYTES = 16
REQUEST_TIMESTAMP_WINDOW_SECONDS = 300

